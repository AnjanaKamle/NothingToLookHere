import { buildLoginDecisionMessage, formatQrPayload } from '@capstone/protocol';
import { runOne, withTransaction } from '../db/sql.js';
import { conflict, forbidden, notFound, unauthorized } from '../http/errors.js';
import { parseEs256PublicKey, verifyEs256 } from '../security/signatures.js';
import {
  decodeBase64Url,
  hmacSha256,
  newNonce,
  newSecret,
  safeEqual,
  sha256,
} from '../security/tokens.js';
import { recordAudit, recordAuditBestEffort } from './audit.js';
import { getUserProfile } from './accounts.js';

// ---------------------------------------------------------------------------------------------
// Watch tokens: let the browser subscribe to Socket.IO events for its own challenge.
// HMAC-SHA256(WATCH_TOKEN_SECRET, "login-watch:v1:<challengeId>"), stateless and unguessable.
// A watch token only lets its holder *hear* the outcome; completing sign-in additionally needs
// the HttpOnly binding cookie.
// ---------------------------------------------------------------------------------------------

export function createWatchToken(config, challengeId) {
  return hmacSha256(config.watchTokenSecret, `login-watch:v1:${challengeId}`).toString('base64url');
}

export function verifyWatchToken(config, challengeId, token) {
  const presented = decodeBase64Url(token);
  if (!presented) return false;
  return safeEqual(presented, Buffer.from(createWatchToken(config, challengeId), 'base64url'));
}

/**
 * Browser starts a QR login (Q-LCH-01). Returns:
 *  - qrPayload:     "capstone-auth:v1:<challengeId>.<nonce>": one-time values only
 *  - bindingSecret: set by the controller as an HttpOnly cookie, never exposed to JavaScript
 *  - watchToken:    for the Socket.IO subscription
 * The challenge id is generated by PostgreSQL's gen_random_uuid() (122 bits from a CSPRNG); the
 * nonce and binding secret are 256-bit values from crypto.randomBytes.
 */
export async function createLoginChallenge(db, config, context) {
  const nonce = newNonce();
  const binding = newSecret();
  const row = await runOne(db, 'Q-LCH-01', [
    nonce.hash,
    binding.hash,
    config.loginChallengeTtlSeconds,
    context.ip,
    context.userAgent,
  ]);
  return {
    challengeId: row.id,
    expiresAt: row.expires_at,
    qrPayload: formatQrPayload({ challengeId: row.id, nonce: nonce.value }),
    watchToken: createWatchToken(config, row.id),
    bindingSecret: binding.value,
  };
}

/** Status for the browser that created the challenge (Q-LCH-04). 404 if the binding is wrong. */
export async function getChallengeStatusForBrowser(db, config, challengeId, bindingSecret) {
  const row = bindingSecret
    ? await runOne(db, 'Q-LCH-04', [
        challengeId,
        sha256(bindingSecret),
        config.loginCompletionWindowSeconds,
      ])
    : null;
  if (!row) throw notFound('challenge_not_found', 'No such login challenge for this browser');
  return { challengeId: row.id, status: row.status, expiresAt: row.expires_at };
}

/** Status by id only, for an authorised Socket.IO watcher (Q-LCH-07). */
export async function getChallengeStatus(db, config, challengeId) {
  const row = await runOne(db, 'Q-LCH-07', [challengeId, config.loginCompletionWindowSeconds]);
  return row && { challengeId: row.id, status: row.status, expiresAt: row.expires_at };
}

/**
 * Phone fetches details of a scanned challenge to show the user (Q-LCH-02). Requires the nonce
 * from the QR code, so a challenge id alone reveals nothing.
 */
export async function inspectChallenge(db, config, challengeId, nonce) {
  const row = await runOne(db, 'Q-LCH-02', [challengeId, sha256(nonce)]);
  if (!row) {
    throw notFound('challenge_unavailable', 'Challenge is unknown, expired or already decided');
  }
  return {
    challengeId: row.id,
    createdAt: row.created_at,
    expiresAt: row.expires_at,
    requester: { ip: row.requester_ip, userAgent: row.requester_user_agent },
    audience: config.authAudience,
  };
}

/**
 * Phone submits a signed approve/deny decision.
 *
 *  1. Load the key by id together with its device and account, and only if all are active
 *     (Q-KEY-06). The key must belong to the phone making the request.
 *  2. Rebuild the exact signed message server-side from the challenge id, the nonce, this
 *     server's audience, the key id and the decision, and verify the signature with the
 *     *registered* public key. A key id alone proves nothing.
 *  3. In one transaction (T-LOGIN-DECIDE): the guarded UPDATE (Q-LCH-03) records the decision
 *     only if the challenge is still pending, unexpired, the nonce matches and the key/device/
 *     account are still active. Concurrent decisions serialize on the row lock; the loser
 *     matches zero rows and gets 409.
 *  4. After commit, notify the waiting browser.
 */
export async function decideChallenge(pool, config, notifier, auth, challengeId, input, context) {
  const key = await runOne(pool, 'Q-KEY-06', [input.keyId]);
  if (!key) throw unauthorized('key_not_active', 'Signing key is unknown or revoked');
  if (key.device_id !== auth.deviceId) {
    throw forbidden('key_not_owned', 'Signing key does not belong to this device');
  }

  const parsedKey = parseEs256PublicKey(key.public_key_spki);
  const signatureDer = decodeBase64Url(input.signature);
  const message = buildLoginDecisionMessage({
    audience: config.authAudience,
    challengeId,
    nonce: input.nonce,
    keyId: input.keyId,
    decision: input.decision,
  });
  const rawSignature =
    parsedKey &&
    signatureDer &&
    verifyEs256({ keyObject: parsedKey.keyObject, message, signatureDer });
  if (!rawSignature) {
    await recordAuditBestEffort(
      pool,
      {
        type: 'login.signature_invalid',
        userId: auth.userId,
        deviceId: auth.deviceId,
        challengeId,
      },
      context,
    );
    throw unauthorized('invalid_signature', 'Signature does not verify with the registered key');
  }

  try {
    await withTransaction(pool, async (client) => {
      const decided = await runOne(client, 'Q-LCH-03', [
        challengeId,
        input.decision,
        input.keyId,
        rawSignature,
        sha256(input.nonce),
      ]);
      if (!decided) {
        throw conflict('challenge_unavailable', 'Challenge is unknown, expired or already decided');
      }
      await runOne(client, 'Q-KEY-05', [input.keyId]);
      await recordAudit(
        client,
        {
          type: input.decision === 'approved' ? 'login.approved' : 'login.denied',
          userId: auth.userId,
          deviceId: auth.deviceId,
          challengeId,
        },
        context,
      );
    });
  } catch (error) {
    if (error.code === 'challenge_unavailable') {
      await recordAuditBestEffort(
        pool,
        {
          type: 'login.replay_rejected',
          userId: auth.userId,
          deviceId: auth.deviceId,
          challengeId,
          details: { step: 'decision' },
        },
        context,
      );
    }
    throw error;
  }

  notifier.loginDecided(challengeId, input.decision);
  return { challengeId, status: input.decision };
}

/**
 * Browser exchanges an approval for a session (T-LOGIN-COMPLETE). Q-LCH-05 consumes the challenge
 * and inserts the session in one statement, at most once per challenge; the audit row commits in
 * the same transaction. Returns the new session token for the cookie.
 */
export async function completeLogin(pool, config, challengeId, bindingSecret, context) {
  if (!bindingSecret)
    throw notFound('challenge_not_found', 'No such login challenge for this browser');
  const sessionToken = newSecret();

  let session;
  try {
    session = await withTransaction(pool, async (client) => {
      const row = await runOne(client, 'Q-LCH-05', [
        challengeId,
        sha256(bindingSecret),
        sessionToken.hash,
        config.sessionTtlSeconds,
        context.ip,
        context.userAgent,
        config.loginCompletionWindowSeconds,
      ]);
      if (!row) {
        throw conflict(
          'challenge_not_approved',
          'Challenge is not approved, already used, or expired',
        );
      }
      await recordAudit(
        client,
        {
          type: 'session.created',
          userId: row.user_id,
          deviceId: row.approved_by_device_id,
          sessionId: row.id,
          challengeId,
        },
        context,
      );
      return row;
    });
  } catch (error) {
    if (error.code === 'challenge_not_approved') {
      await recordAuditBestEffort(
        pool,
        { type: 'login.replay_rejected', challengeId, details: { step: 'complete' } },
        context,
      );
    }
    throw error;
  }

  return {
    sessionToken: sessionToken.value,
    session: { id: session.id, expiresAt: session.expires_at },
    user: await getUserProfile(pool, session.user_id),
  };
}
